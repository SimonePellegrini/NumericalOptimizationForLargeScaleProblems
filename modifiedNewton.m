function [gradfk_norm,fk,errorSeq,x_k,k,xseq] = modifiedNewton(x_0, f, gradf,hessianf, max_iter, tolgrad, c1, rho, btmax, beta)

    % INPUT:
    %
    % x_0      : initial point of the algorithm
    % f        : objective function
    % gradf    : gradient of the objective function
    % hessianf : Hessian of the objective function
    % max_iter : maximum number of allowed iterations
    % tolgrad  : tolerance on the norm of the gradient
    % c1       : Armijo condition parameter
    % rho      : step size reduction factor for backtracking
    % btmax    : maximum number of backtracking iterations
    % beta     : regularization parameter for the Hessian
    %
    % OUTPUT:
    %
    % gradfk_norm : norm of the gradient at the final iterate
    % fk          : value of the objective function at the final iterate
    % errorSeq    : sequence of differences between consecutive iterates
    % x_k         : final point computed by the algorithm
    % k           : number of iterations performed
    % xseq        : sequence of iterates generated by the algorithm

    %computes the value used in the armijo condition
    farmijo = @(fk, alpha, c1_gradfk_pk) fk + alpha * c1_gradfk_pk;
    
    %set up the starting point
    x_k = x_0;
    xseq = x_k(:)';
    errorSeq = zeros(max_iter,1);
    fk = f(x_k);

    

    %computes the gradient to build the second order Taylor's expansion
    %gradfk = gradf(x_k);
    gradfk = gradf(x_k);
    %computes the hessian to build the second order Taylor's expansio
    hessian = hessianf(x_k);
  
    %computes the norm of the gradient
    gradfk_norm = norm(gradfk);
    
    %variable that counts the number of iterations
    k = 0;
   
    %main loop
    while k < max_iter && gradfk_norm >= tolgrad
       
        k = k + 1;
        
        %make the hessian positive definite

        t_k = 0;
        p=1;
        min_diag = min(diag(hessian));
        
        %check if is it possible that the hessian is sym. pos. definite
        if min_diag<=0
            t_k = beta-min_diag;
        end
        
        %loop until we compute a matrix that is sym. pos. definite
        while p ~= 0
            %update the matrix
            B_k = hessian+t_k*speye(size(hessian,1));
            %try to compute the cholesky factorization
            [R,p] = chol(B_k);
            t_k = max(2*t_k,beta); 
        end
        

        %compute the best vector p using the matrix obtained from the
        %cholesky factorization
        
        y = -R'\gradfk;
        pk = R\y;
        
        
         %computes phi'(0)
        c1_gradfk_pk = c1 * gradfk' * pk;
        bt = 0;

        %Update xnew and fnew with the new point computed
        alpha = 1;
        xnew = x_k+alpha*pk;
        fnew = f(xnew);
        
         
        %Armijo + BackTracking to compute the direction of the search
        while bt < btmax && fnew > farmijo(fk, alpha, c1_gradfk_pk)
            % Redue the value of alpha
            alpha = rho * alpha;
            % Update xnew and fnew w.r.t. the reduced alpha
            xnew = x_k + alpha * pk;
            fnew = f(xnew);
            
            % Increase the counter by one
            bt = bt + 1;
        end
        
        %if we didn't find a new point satisfying the armijo condition then
        %end the loop
        if bt == btmax && fnew > farmijo(fk, alpha, c1_gradfk_pk)
            display("loop ended!")
            break
        end
        
        errorSeq(k) = norm(x_k-xnew);
        x_k = xnew;

        % update the value of the function, the gradient, the hessian and
        % the norm of the gradient.
        xseq(end+1,:) = x_k(:)';
        fk = fnew;
        gradfk = gradf(x_k);
        gradfk_norm = norm(gradfk); 
        hessian = hessianf(x_k);
    
        
    end
end

